#
# YubiKey — lock the session when the key is removed, wake the display when it
# is inserted, and enable the smartcard daemon for PIV / GPG / ykman.
#
# /etc is a writable overlay on Bazzite (Fedora Atomic), so udev rules and
# systemd units placed there persist across rebases.
#
