  printf '%s\n' "$ydotoold_unit" | sudo tee /etc/systemd/system/ydotoold.service > /dev/null
  sudo systemctl daemon-reload
fi
sudo systemctl enable --now ydotoold.service

yubikey_rules="# Lock all sessions when any YubiKey (vendor 1050) is removed
ACTION==\"remove\", ENV{ID_BUS}==\"usb\", ENV{ID_VENDOR_ID}==\"1050\", RUN+=\"/usr/bin/loginctl lock-sessions\"

# Wake the display when any YubiKey is inserted
ACTION==\"add\", ENV{ID_BUS}==\"usb\", ENV{ID_VENDOR_ID}==\"1050\", ENV{YDOTOOL_SOCKET}=\"${YDOTOOL_SOCKET_PATH}\", RUN+=\"/usr/bin/ydotool key 42:1 42:0\""
if ! diff -q <(printf '%s\n' "$yubikey_rules") /etc/udev/rules.d/80-yubikey.rules &>/dev/null; then
