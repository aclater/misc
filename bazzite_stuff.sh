#
# rpm-ostree layering — CLI tools, GNOME shell extensions, and system-level
# packages in a single transaction.
#   --idempotent: succeed even if packages are already in the base image.
#   --apply-live: make layered packages available immediately without rebooting.
# If --apply-live fails (rare), the packages are staged for the next boot and
# the script continues with user-space setup.
#
OSTREE_OK=1
if ! sudo rpm-ostree install --idempotent --apply-live \
  gnome-shell-extension-common gnome-shell-extension-user-theme \
  gnome-shell-extension-freon gnome-shell-extension-no-overview \
  gnome-shell-extension-dash-to-dock \
  gnome-shell-extension-appindicator gnome-shell-extension-caffeine \
  gnome-shell-extension-blur-my-shell gnome-shell-extension-just-perfection \
  gnome-tweaks gnome-extensions-app \
  git btop fastfetch solaar mpv \
  yt-dlp 7zip unrar \
  rsms-inter-vf-fonts \
  fuse-libs \
  ydotool pcsc-lite pcsc-lite-ccid pam-u2f pamu2fcfg yubikey-manager \
  opensc nss-tools openssl gnupg2 unzip \
  fprintd fprintd-pam \
  vim-enhanced; then
  echo "WARN: --apply-live failed; layered packages are staged for next boot."
  echo "      GNOME extensions and some CLI tools may not work until you reboot."
  OSTREE_OK=0
fi

#
# Default editor — set vim for the current user without touching the immutable
# base. Uses systemd's environment.d so it applies to all login sessions.
#
mkdir -p ~/.config/environment.d
