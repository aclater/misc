#
# Fleet verification + card diagnostics
#
cat > ~/.local/bin/verify-pki-trust.sh <<'VERIFYEOF'
#!/usr/bin/env bash
#
# verify-pki-trust.sh [path/to/piv-auth-leaf.pem]
#
# Card-free verification that a machine can validate USDA PIV and DoD chains.
# Exit code 0 = all checks pass, nonzero = something failed.
#
set -uo pipefail

DB_DIR="$HOME/.pki/nssdb"
DB="sql:$DB_DIR"
SSP_AIA_URL="http://sspweb.managed.entrust.com/AIA/CertsIssuedToEMSSSPCA.p7c"
