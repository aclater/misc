#!/usr/bin/env bash
#
# Bazzite (GNOME) post-install setup
# Flatpak for GUI apps; rpm-ostree layering for CLI/system tools only.
# Signal uses the official AppImage (GPG-verified).
#
# Bazzite already ships with: Steam, GPU drivers (incl. NVIDIA), multimedia
# codecs, RPMFusion repos, and auto-updates — those sections from the regular
# Fedora script are omitted entirely.
#
# Usage (fresh install): download this ONE file and run it as your normal user
# inside a GNOME session. Don't pipe it to bash from curl — download, read, run:
#   curl -fLO https://raw.githubusercontent.com/<you>/<repo>/main/bazzite_stuff.sh
#   chmod +x bazzite_stuff.sh && ./bazzite_stuff.sh
# Everything else (updaters, PKI importers, verifiers) is generated by this
# script into ~/.local/bin and /etc/systemd — nothing else to check out.
#
set -euo pipefail

if [ "$EUID" -eq 0 ]; then
  echo "Don't run this with sudo / as root. Run it as your normal user:" >&2
  echo "    ./bazzite_stuff.sh" >&2
  echo "It will prompt for your password when it reaches the first sudo step." >&2
  exit 1
fi

if [ -z "${DBUS_SESSION_BUS_ADDRESS:-}" ]; then
  echo "No D-Bus session bus found (DBUS_SESSION_BUS_ADDRESS is unset)." >&2
  echo "This script sets GNOME preferences with gsettings and must run inside a" >&2
  echo "graphical GNOME session — not over SSH or a plain TTY. Log in to the" >&2
  echo "desktop, open a terminal there, and re-run it." >&2
  exit 1
fi

#
# Flatpak GUI apps (Flathub is pre-configured on Bazzite)
#
flatpak install --noninteractive flathub \
