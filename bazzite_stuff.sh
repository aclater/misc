  echo 'EDITOR=vim' >> ~/.config/environment.d/editor.conf
fi

#
# Enable GNOME shell extensions at startup.
# Installing the RPM only drops files in /usr/share/gnome-shell/extensions;
# they still have to be added to org.gnome.shell enabled-extensions. We write
# the gsettings key directly so it works even before the shell has rescanned
# (gnome-extensions enable would refuse until then) and survives a re-login.
#
gext_enable() {
  local uuid="$1" cur new
  cur=$(gsettings get org.gnome.shell enabled-extensions)
  case "$cur" in
    *"'$uuid'"*)     ;;
    "@as []"|"[]")   gsettings set org.gnome.shell enabled-extensions "['$uuid']" ;;
    *)               gsettings set org.gnome.shell enabled-extensions "${cur%]}, '$uuid']" ;;
  esac
  cur=$(gsettings get org.gnome.shell disabled-extensions)
  if [[ "$cur" == *"'$uuid'"* ]]; then
    new=$(python3 -c 'import ast, sys
v, u = sys.argv[1], sys.argv[2]
lst = ast.literal_eval(v) if v.lstrip().startswith("[") else []
print("[" + ", ".join(repr(x) for x in lst if x != u) + "]")' "$cur" "$uuid")
    gsettings set org.gnome.shell disabled-extensions "$new"
  fi
}
